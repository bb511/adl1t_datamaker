# ANSI escape codes for colouring the logs. A coloured string has to be closed with
# ENDC, otherwise the colour bleeds into everything the terminal prints afterwards.


class tcols:
    HEADER = "\033[95m"
    OKBLUE = "\033[94m"
    OKCYAN = "\033[96m"
    OKGREEN = "\033[92m"
    WARNING = "\033[93m"
    FAIL = "\033[91m"
    ENDC = "\033[0m"
    BOLD = "\033[1m"
    UNDERLINE = "\033[4m"
